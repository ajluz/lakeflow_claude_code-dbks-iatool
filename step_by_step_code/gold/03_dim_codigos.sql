CREATE OR REFRESH LIVE TABLE dataslight_dev.gold.dim_codigos (
    sk_codigos BIGINT GENERATED BY DEFAULT AS IDENTITY,
    origem_usuario STRING,
    local_acesso STRING,
    forma_pagamento STRING,
    percentual_disconto STRING,
    data_carga TIMESTAMP DEFAULT current_timestamp()
)
TBLPROPERTIES ("quality" = "gold")
AS 
  SELECT DISTINCT
      v.origem origem_usuario,
      CASE WHEN v.origem = 'ARQUIVO' 
        THEN 'Não se aplica' 
      ELSE a.local_acesso END AS local_acesso,
      v.forma_pagamento,
      coalesce(v.percentual_disconto,'Não se aplica') AS percentual_disconto
  FROM dataslight_dev.silver.tb_venda AS v
  CROSS JOIN dataslight_dev.silver.tb_acesso AS a