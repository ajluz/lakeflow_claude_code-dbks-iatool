-- Feature 010-gold-dim-tempo: cria e preenche a dimensão de calendário
-- workspace.gold.dim_tempo, com uma linha por dia de 2021-01-01 a 2030-12-31.
--
-- É um dado de referência estático: fica fora do pipeline e é carregado por este
-- script (constituição, Princípio I).
--
-- O script pode ser executado quantas vezes for preciso. Ele só insere os dias que
-- ainda não estão na tabela e nunca reescreve uma linha existente; por isso o
-- sk_tempo de um dia, gerado por identity, nunca muda, e uma segunda execução não
-- altera nada. Para estender o período, basta mudar v_fim e executar de novo.
--
-- Como executar (o profile é sempre escolhido por quem executa):
--   databricks experimental aitools tools query explorations/setup/04_dim_tempo.sql --profile <profile>
--
-- Pré-requisito: o schema workspace.gold (passo 01_schemas.sql).
--
-- Se a tabela já tiver algum dia repetido, o script para com erro antes de inserir
-- qualquer linha. Ele nunca exclui a tabela nem apaga linhas.
--
-- O resultado é uma linha de resumo: linhas, dias, membros, primeiro e último dia e
-- dias repetidos.

BEGIN
  DECLARE v_inicio DATE DEFAULT DATE'2021-01-01';
  DECLARE v_fim DATE DEFAULT DATE'2030-12-31';
  DECLARE v_repetidos BIGINT DEFAULT 0;
  DECLARE v_msg STRING DEFAULT '';

  -- IF NOT EXISTS: uma tabela que já existe nunca é substituída, e suas chaves
  -- continuam as mesmas.
  CREATE TABLE IF NOT EXISTS workspace.gold.dim_tempo (
    sk_tempo BIGINT GENERATED BY DEFAULT AS IDENTITY,
    data DATE,
    ano INT,
    mes STRING,
    mes_ano INT,
    dia_semana_int INT,
    dia_semana STRING,
    fl_dia_semana BOOLEAN,
    dia_mes INT,
    fl_ultimo_dia_mes BOOLEAN,
    dia_ano INT,
    semana_ano INT,
    bimestre INT,
    trimestre INT,
    semestre INT,
    data_carga TIMESTAMP
  )
  COMMENT 'Calendário: uma linha por dia de 2021-01-01 a 2030-12-31, mais os membros -1 (Desconhecido) e -2 (Não se aplica). Carregada por explorations/setup/04_dim_tempo.sql.'
  TBLPROPERTIES ("quality" = "gold");

  -- Dias repetidos (por exemplo, deixados pela antiga célula de functions.py, que
  -- inseria o calendário a cada execução) multiplicariam as linhas dos fatos. O
  -- script para sem alterar nada, em vez de apagar linhas: qual cópia manter seria
  -- arbitrário, e excluir a tabela é decisão do dono.
  SET v_repetidos = (
    SELECT count(data) - count(DISTINCT data)
    FROM workspace.gold.dim_tempo
  );
  IF v_repetidos > 0 THEN
    SET v_msg = concat(
      'workspace.gold.dim_tempo has ', CAST(v_repetidos AS STRING),
      ' repeated day(s); nothing was changed. Drop the table with approval from the owner',
      ' and run explorations/setup/04_dim_tempo.sql again'
    );
    SIGNAL SQLSTATE '45000'
      SET MESSAGE_TEXT = v_msg;
  END IF;

  -- Membros: -1 (Desconhecido) e -2 (Não se aplica), para que um fato sem data, ou
  -- para o qual a data não se aplica, ainda aponte para uma linha. As chaves fixas
  -- são permitidas por GENERATED BY DEFAULT; são negativas e nunca colidem com as
  -- geradas pela identity. data e os demais atributos ficam vazios.
  INSERT INTO workspace.gold.dim_tempo (sk_tempo, mes, dia_semana, data_carga)
  SELECT
    m.sk_tempo,
    m.rotulo,
    m.rotulo,
    current_timestamp()
  FROM VALUES
    (CAST(-1 AS BIGINT), 'Desconhecido'),
    (CAST(-2 AS BIGINT), 'Não se aplica') AS m(sk_tempo, rotulo)
  WHERE NOT EXISTS (
    SELECT 1
    FROM workspace.gold.dim_tempo AS t
    WHERE t.sk_tempo = m.sk_tempo
  );

  -- Dias: insere somente os que faltam. Uma nova execução não acrescenta nada, e o
  -- sk_tempo é gerado pela identity apenas na primeira inserção de cada dia.
  -- dia_semana_int: 1 = domingo ... 7 = sábado. semana_ano: semana ISO.
  INSERT INTO workspace.gold.dim_tempo (
    data,
    ano,
    mes,
    mes_ano,
    dia_semana_int,
    dia_semana,
    fl_dia_semana,
    dia_mes,
    fl_ultimo_dia_mes,
    dia_ano,
    semana_ano,
    bimestre,
    trimestre,
    semestre,
    data_carga
  )
  SELECT
    d.data,
    year(d.data),
    element_at(
      array('janeiro', 'fevereiro', 'março', 'abril', 'maio', 'junho',
            'julho', 'agosto', 'setembro', 'outubro', 'novembro', 'dezembro'),
      month(d.data)
    ),
    month(d.data),
    dayofweek(d.data),
    element_at(
      array('domingo', 'segunda-feira', 'terça-feira', 'quarta-feira',
            'quinta-feira', 'sexta-feira', 'sábado'),
      dayofweek(d.data)
    ),
    dayofweek(d.data) BETWEEN 2 AND 6,
    dayofmonth(d.data),
    d.data = last_day(d.data),
    dayofyear(d.data),
    weekofyear(d.data),
    CAST(ceil(month(d.data) / 2) AS INT),
    quarter(d.data),
    CAST(ceil(month(d.data) / 6) AS INT),
    current_timestamp()
  FROM (SELECT explode(sequence(v_inicio, v_fim, INTERVAL 1 DAY)) AS data) AS d
  WHERE NOT EXISTS (
    SELECT 1
    FROM workspace.gold.dim_tempo AS t
    WHERE t.data = d.data
  );

  SELECT
    count(*)                         AS linhas,
    count(data)                      AS dias,
    count_if(sk_tempo < 0)           AS membros,
    min(data)                        AS primeiro_dia,
    max(data)                        AS ultimo_dia,
    count(data) - count(DISTINCT data) AS dias_repetidos
  FROM workspace.gold.dim_tempo;
END
