CREATE OR REFRESH LIVE TABLE workspace.gold.dim_usuario (
    sk_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_uuid STRING,
    nome_usuario STRING, 
    email_usuario STRING,
    idade_usuario INT,
    sexo_usuario STRING,
    estado_usuario STRING,
    profissao_usuario STRING,
    empresa_usuario STRING,
    origem STRING,
    dt_carga TIMESTAMP DEFAULT current_timestamp()
)
TBLPROPERTIES ("quality" = "gold")
AS 
  SELECT 
    *
    EXCEPT(data_carga)
  FROM workspace.silver.tb_usuario;